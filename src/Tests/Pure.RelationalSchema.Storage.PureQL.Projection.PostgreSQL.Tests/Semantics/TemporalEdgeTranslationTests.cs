    [Theory]
    [MemberData(nameof(Sweeps))]
    public void FunctionsOverAGeneratedSeriesAreComputedByPostgreSqlAsInMemory(
        string sweep
    )
    {
        PureQLQuery query = sweep switch
        {
            "calendar from 2024-01-01" => Sweep(6, "day", "date", "1", 400),
            "calendar from 0001-01-01" => Sweep(8, "day", "date", "1", 40),
            "calendar back from 9999-12-31" => Sweep(9, "day", "date", "-1", 40),
            "clock every 862.123457 seconds" => Sweep(
                2,
                "clock",
                "time",
                "\"862.123457\"",
                120
            ),
            "clock every microsecond" => Sweep(3, "clock", "time", "\"0.000001\"", 30),
            "instants every 615432.987654 seconds" => Sweep(
                6,
                "at",
                "datetime",
                "\"615432.987654\"",
                200
            ),
            _ => Sweep(9, "at", "datetime", "\"-0.999999\"", 30),
        };

        IReadOnlyList<string> rows = Translation.Translated(_database, query);

        Assert.True(rows.Count > 30);
    }

