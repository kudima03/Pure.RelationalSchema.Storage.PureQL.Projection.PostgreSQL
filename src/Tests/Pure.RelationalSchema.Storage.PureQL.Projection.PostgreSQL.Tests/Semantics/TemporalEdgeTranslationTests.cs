    private static TheoryData<string, string> Crossed(
        (string Name, string Type)[] functions,
        IEnumerable<string> operands
    )
    {
        TheoryData<string, string> data = [];

        foreach (string operand in operands)
        {
            foreach ((string name, _) in functions)
            {
                data.Add(name, operand);
            }
        }

        return data;
    }

    private static string Applied(
        (string Name, string Type)[] functions,
        string function,
        string operand
    )
    {
        string type = functions.Single(candidate => candidate.Name == function).Type;
        return Unary(function, type, false, operand);
    }

    private static string AddDays(string date, string perId)
    {
        return Op(
            "dateAddDays",
            "date",
            false,
            ("operand", Literal("date", $"\"{date}\"")),
            ("days", Multiplied("integer", perId))
        );
    }

    private static string AddSeconds(
        string type,
        string value,
        string secondsType,
        string perId
    )
    {
        return Op(
            type == "time" ? "timeAddSeconds" : "datetimeAddSeconds",
            type,
            false,
            ("operand", Literal(type, $"\"{value}\"")),
            ("seconds", Multiplied(secondsType, perId))
        );
    }

    // The id times a literal step.
    private static string Multiplied(string type, string step)
    {
        return "{\"operator\": \"multiply\", \"type\": "
            + Type(type)
            + ", \"values\": ["
            + Field("id")
            + ", "
            + Literal(type, step)
            + "]}";
    }

    // The parameter (or literal) plus id x 0 seconds: a time PostgreSQL
