    // The operand of a computed datetime keeps its fraction in PostgreSQL:
    // only a stored datetime is read without it.
    [Fact]
    public void ComputedDatetimeKeepsItsFractionOfASecond()
    {
        IReadOnlyList<string> rows = Translation.Translated(
            _database,
            Valued(
                Unary(
                    "microsecond",
                    "integer",
                    false,
                    Datetimes["2024-02-29T23:59:59.999999Z + 0.0000005 s per id"]
                )
            )
        );

        Assert.Equal("1 | 0", rows[1]);
        Assert.Equal("10 | 4", rows[10]);
    }

