    private static string Over(string[] partitionBy, string[] orderBy)
    {
        return "{\"partitionBy\": ["
            + string.Join(", ", partitionBy)
            + "]"
            + (
                orderBy.Length == 0
                    ? ""
                    : ", \"orderBy\": ["
                        + string.Join(
                            ", ",
                            orderBy.Select(key => "{\"expression\": " + key + "}")
                        )
                        + "]"
            )
            + "}";
    }

    // The query through the rewriting dataset and in memory with the fine
    // parameters bound: the same result, run as expected.
    private IReadOnlyList<string> WithParameters(
        PureQLQuery query,
        QueryExecution execution
    )
    {
        PureQLProjection actual = new(_database.Rewriting, query, FineParameters);
        IReadOnlyList<string> result = ResultText.Of(actual, true);

        Assert.Equal(
            ResultText.Of(
                new PureQLProjection(PostgreSqlDatabase.InMemory, query, FineParameters),
                true
            ),
            result
        );
        Assert.Equal(execution, actual.Execution);

        return result;
    }

    private static readonly IReadOnlyDictionary<string, IParameter> FineParameters =
        new Dictionary<string, IParameter>
        {
            // 23:59:59.9999995 and 00:30:00.0000005: half a microsecond.
            ["fine_time"] = new TimeParameter(new Time(new TimeOnly(863_999_999_995L))),
            ["tick_time"] = new TimeParameter(new Time(new TimeOnly(18_000_000_005L))),
            // 2024-02-29T23:59:59.9999999 and 9999-12-31T23:59:59.9999999.
            ["fine_at"] = new DateTimeParameter(
                new DateTime(
                    new Date(new DateOnly(2024, 2, 29)),
                    new Time(new TimeOnly(863_999_999_999L))
                )
            ),
            ["last_at"] = new DateTimeParameter(
                new DateTime(
                    new Date(new DateOnly(9999, 12, 31)),
                    new Time(new TimeOnly(863_999_999_999L))
                )
            ),
            ["leap_day"] = new DateParameter(new Date(new DateOnly(2024, 2, 29))),
        };

    private static string Unary(
        string name,
        string type,
        bool nullable,
        string operand,
        params (string Name, string Value)[] more
    )
    {
        return Op(name, type, nullable, [("operand", operand), .. more]);
    }

    private static string Op(
        string name,
        string type,
        bool nullable,
        params (string Name, string Value)[] operands
    )
    {
        return "{\"operator\": \""
            + name
            + "\", \"type\": "
            + Type(type, nullable)
            + string.Concat(
                operands.Select(operand => $", \"{operand.Name}\": {operand.Value}")
            )
            + "}";
    }
