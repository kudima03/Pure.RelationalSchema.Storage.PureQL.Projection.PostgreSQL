    private static string RangeKey(string key)
    {
        string[] parts = key.Split(' ');
        string type = parts[0] switch
        {
            "quarter" or "dayOfWeek" or "microsecond" => "integer",
            _ => parts[1] == "day" ? "date" : "datetime",
        };

        return Unary(parts[0], type, true, Field(parts[1]));
    }

    private static IEnumerable<string> RangeAggregates(
        string key,
        string range,
        bool descending
    )
    {
        string over =
            "{\"partitionBy\": ["
            + Field("grp")
            + "], \"orderBy\": [{\"expression\": "
            + key
            + (descending ? ", \"direction\": \"desc\"" : "")
            + "}], \"range\": "
            + range
            + "}";

        yield return "{\"operator\": \"count\", \"type\": "
            + Type("integer")
            + ", \"over\": "
            + over
            + "}";
        yield return "{\"operator\": \"min\", \"type\": "
            + Type("integer")
            + ", \"selector\": "
            + Field("id")
            + ", \"over\": "
            + over
            + "}";
        yield return "{\"operator\": \"max\", \"type\": "
            + Type("integer")
            + ", \"selector\": "
            + Field("id")
            + ", \"over\": "
            + over
            + "}";
    }

