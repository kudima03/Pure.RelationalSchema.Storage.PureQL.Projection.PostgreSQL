    // A recursive series from the value of one reading: k from 0 to the
    // steps, each value the one before plus the step (days or seconds), with
    // every rewritten function of its type.
    private static PureQLQuery Sweep(
        long seedId,
        string field,
        string type,
        string step,
        int steps
    )
    {
        string k = Aliased("sweep", "k", "integer", false);
        string v = Aliased("sweep", "v", type, false);
        string next = type switch
        {
            "date" => Op(
                "dateAddDays",
                "date",
                false,
                ("operand", v),
                ("days", Literal("integer", step))
            ),
            "time" => Op(
                "timeAddSeconds",
                "time",
                false,
                ("operand", v),
                ("seconds", Literal("decimal", step))
            ),
            _ => Op(
                "datetimeAddSeconds",
                "datetime",
                false,
                ("operand", v),
                ("seconds", Literal("decimal", step))
            ),
        };
        (string Name, string Type)[] functions = type switch
        {
            "date" => DateFunctions,
            "time" => TimeFunctions,
            _ => DatetimeFunctions,
        };
        string seed = Op(
            "coalesce",
            type,
            false,
            (
                "values",
                "["
                    + Field(field)
                    + ", "
                    + Literal(
                        type,
                        type switch
                        {
                            "date" => "\"2000-01-01\"",
                            "time" => "\"00:00:00\"",
                            _ => "\"2000-01-01T00:00:00Z\"",
                        }
                    )
                    + "]"
            )
        );
        string selected = string.Join(
            ", ",
            functions.Select(function =>
                $$"""{"alias": "{{function.Name}}", "expression": {{Unary(
                    function.Name,
                    function.Type,
                    false,
                    v
                )}}}"""
            )
        );

        string recursive =
            "{\"seed\": "
            + SweepSeed(seedId, seed)
            + ", \"next\": "
            + SweepNext(k, next, steps)
            + ", \"maxDepth\": "
            + (steps + 5)
            + "}";

        return Query(
            $$"""
            {
              "subqueries": [{"name": "sweep", "recursive": {{recursive}}}],
              "from": {"subquery": "sweep"},
              "select": [
                {"alias": "k", "expression": {{k}}},
                {"alias": "v", "expression": {{v}}},
                {{selected}}
              ],
              "orderBy": [{"expression": {{k}}}]
            }
            """
        );
    }

    private static string SweepSeed(long seedId, string seed)
    {
        return $$"""
            {
              "from": {"entity": "t.readings"},
              "where": {{Compared(
                "equal",
                Field("id"),
                Literal("integer", $"{seedId}")
            )}},
              "select": [
                {"alias": "k", "expression": {{Literal("integer", "0")}}},
                {"alias": "v", "expression": {{seed}}}
              ]
            }
            """;
    }

    private static string SweepNext(string k, string next, int steps)
    {
        string added =
            "{\"operator\": \"add\", \"type\": "
            + Type("integer")
            + ", \"values\": ["
            + k
            + ", "
            + Literal("integer", "1")
            + "]}";

        return $$"""
            {
              "from": {"subquery": "sweep"},
              "where": {{Compared("lessThan", k, Literal("integer", $"{steps}"))}},
              "select": [
                {"alias": "k", "expression": {{added}}},
                {"alias": "v", "expression": {{next}}}
              ]
            }
            """;
    }

